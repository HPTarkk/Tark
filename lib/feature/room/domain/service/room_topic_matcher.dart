/// Picks the [RoomTopic] a Room's name is about, or null when nothing in it
/// says.
///
/// Persian first, English alongside, and Persian written in Latin letters
/// ("safar", "rafigha") too. The name is folded before matching, so the
/// spellings a keyboard can produce for the same word all read the same:
///
///  * Arabic letter forms fold to Persian ones (yeh, kaf, heh, alef, waw).
///    Harakat, tatweel and the combining hamza above are removed.
///  * A ZWNJ (نیم‌فاصله) reads as a space, so «هم‌سفر», «هم سفر» and «همسفر»
///    are one word to the patterns.
///  * Persian and Arabic digits read as ASCII, so «۱۱۵» is the emergency
///    number and «پی‌اس ۵» a console.
///  * Case, camelCase ("RoadTrip") and punctuation (`_ - . #`) go.
///
/// An emoji in the name is the clearest signal there is, so the first one
/// with a meaning wins outright ("⚽ خانواده" is football). Otherwise the
/// topics are tried in [RoomTopic]'s order and the first that matches wins:
/// emergencies before anything, then what the group does (a "family road
/// trip" is a drive), then who it is ("family"), and plain "friends" last.
///
/// Every word is matched whole. Persian words also take the endings people
/// add (ها، های، ی، ان، ا …), but never a letter that makes another word:
/// «کار» is work and «کاروان» is a convoy; «سفر» is a trip and «سفره» is a
/// meal. Short words that are also common names or other words (درسا, پس,
/// گل) are left out or matched exactly.
///
/// Pure and synchronous: patterns compile once, and the last few hundred
/// names are remembered, so calling it from `build` costs nothing.
abstract final class RoomTopicMatcher {
  /// The topic [name] is about, or null.
  static RoomTopic? match(String name) {
    if (_cache.containsKey(name)) {
      // Re-inserted so the names in use stay the newest.
      final topic = _cache.remove(name);
      return _cache[name] = topic;
    }
    final topic = _resolve(name);
    _cache[name] = topic;
    if (_cache.length > _cacheLimit) _cache.remove(_cache.keys.first);
    return topic;
  }

  /// The last names asked about, null results included, oldest first.
  static final LinkedHashMap<String, RoomTopic?> _cache = LinkedHashMap();
  static const _cacheLimit = 256;

  /// Forgets remembered names. For tests.
  static void clearCache() => _cache.clear();

  static RoomTopic? _resolve(String name) {
    if (name.trim().isEmpty) return null;
    final fromEmoji = _emojiTopic(name);
    if (fromEmoji != null) return fromEmoji;
    final text = normalize(name);
    if (text.isEmpty) return null;
    for (final rule in _rules) {
      if (rule.pattern.hasMatch(text)) return rule.topic;
    }
    return null;
  }

  /// [name] as the patterns see it: folded letters and digits, lower case,
  /// single spaces. Exposed for tests.
  static String normalize(String name) {
    final split = name.replaceAllMapped(_camelHump, (m) => '${m[1]} ${m[2]}');
    final folded = _fold(split.toLowerCase(), separators: true);
    return folded.replaceAll(_spaces, ' ').trim();
  }

  static final _camelHump = RegExp(r'(\p{Ll})(\p{Lu})', unicode: true);
  static final _spaces = RegExp(r'\s+');

  /// Folds Arabic letter forms, digits and invisible marks. Applied to the
  /// patterns as well (without [separators]) so they can be written in
  /// ordinary Persian and still match every spelling.
  static String _fold(String input, {required bool separators}) {
    final out = StringBuffer();
    for (final rune in input.runes) {
      final mapped = _foldRune(rune, separators: separators);
      if (mapped != null) out.writeCharCode(mapped);
    }
    return out.toString();
  }

  static int? _foldRune(int rune, {required bool separators}) {
    // Persian (۰–۹) and Arabic-Indic (٠–٩) digits.
    if (rune >= 0x06F0 && rune <= 0x06F9) return 0x30 + rune - 0x06F0;
    if (rune >= 0x0660 && rune <= 0x0669) return 0x30 + rune - 0x0660;
    // Harakat, the hamza above, the superscript alef, tatweel.
    if (rune >= 0x064B && rune <= 0x065F) return null;
    if (rune == 0x0670 || rune == 0x0640) return null;
    switch (rune) {
      case 0x064A || 0x0649 || 0x0626:
        return 0x06CC; // ی
      case 0x0643: // ك
        return 0x06A9; // ک
      case 0x0629 || 0x06C0:
        return 0x0647; // ه
      case 0x0623 || 0x0625 || 0x0622 || 0x0671:
        return 0x0627; // ا
      case 0x0624:
        return 0x0648; // و
      case 0x200C: // ZWNJ: a half-space reads as a space.
        return separators ? 0x20 : rune;
      case 0x200B || 0x200D || 0x200E || 0x200F || 0xFEFF || 0xFE0F:
        // Zero-width space and joiner, direction marks, BOM, emoji style.
        return separators ? null : rune;
    }
    if (separators && _separators.contains(rune)) return 0x20;
    return rune;
  }

  /// Punctuation people put between words, read as a space.
  static final Set<int> _separators = {
    for (final c in r'_-–—.,;:!?¡¿/\|()[]{}<>"“”«»#@+&*~^=%$'.runes) c,
    0x060C, // ،
    0x061B, // ؛
    0x061F, // ؟
    0x066B, // ٫
    0x066C, // ٬
    0x0027, // '
    0x2019, // ’
  };

  static RoomTopic? _emojiTopic(String name) {
    for (final rune in name.runes) {
      if (rune < 0x2000) continue;
      final topic = _emoji[rune];
      if (topic != null) return topic;
    }
    return null;
  }

  /// Persian endings a word may take: plurals (ها، های، ان، colloquial ا),
  /// the ی of an adjective or an indefinite, and «مون/تون/شون» (our/your/
  /// their). The plural may stand apart («گرگ ها») or be joined.
  static const _faEnding =
      '(?: ?ها(?:ی|یی|مون|تون|شون)?|ی|یی|ای|ان|ا|مون|تون|شون)?';

  static final List<_Rule> _rules = [
    for (final spec in _specs) _Rule(spec.topic, _compile(spec)),
  ];

  static RegExp _compile(_Spec spec) {
    final alternatives = <String>[
      if (spec.en.isNotEmpty)
        '(?<![a-z])(?:${spec.en.join('|')})(?:s|es)?(?![a-z])',
      if (spec.fa.isNotEmpty)
        '(?<!\\p{L})(?:${_fold(spec.fa.join('|'), separators: false)})'
            '$_faEnding(?!\\p{L})',
      if (spec.faExact.isNotEmpty)
        '(?<!\\p{L})(?:${_fold(spec.faExact.join('|'), separators: false)})'
            '(?!\\p{L})',
    ];
    return RegExp(alternatives.join('|'), unicode: true);
  }

